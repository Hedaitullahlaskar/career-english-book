"""Shared helpers for the role-engine curriculum store (editorial/curriculum/).

The store is architecture-validation work for pilot U-1. It never touches book-data.json, the
website, the PDF or the publication gates, and nothing here compiles or publishes content.

Curriculum text is generated by ChatGPT (author decision D-U10). These tools build the requests,
validate and store the responses, assign IDs and codes, run AI QA, compose and test search.
"""
